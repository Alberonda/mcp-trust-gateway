/** Pure vector math — ranks find_tool's cached candidates by similarity to a query
 *  embedding. Assumes both vectors have the same dimensionality (always true here: every
 *  embedding comes from the same Embedder — see ports/Embedder.ts). */
export function cosineSimilarity(a: readonly number[], b: readonly number[]): number {
  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
